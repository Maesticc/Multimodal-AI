"""Run every question in examples/questions.json through the full pipeline and save outputs.

Writes
- examples/outputs/answers.md     readable report: answer, citations, retrieved passages
- examples/outputs/answers.jsonl  full records (prompt, scores, timings) for inspection
- a diagnostic table separating retrieval failures from generation failures:
    retrieval hit? | answer has key facts? | abstained? | citations point at relevant pages?
"""

from __future__ import annotations

import json

from .config import Settings
from .evaluate import OUT_DIR, answer_has_facts, evidence_rank, first_relevant_rank, load_questions
from .generate import get_llm
from .pipeline import RAGPipeline, render_markdown
from .retrieve import RetrievedChunk
from .ingest import Chunk


def _diagnose(q: dict, res: dict) -> dict:
    passages = [
        RetrievedChunk(chunk=Chunk(**p["chunk"]), rank=p["rank"], score=p["score"]) for p in res["retrieval"]["passages"]
    ]
    answerable = bool(q["relevant"])
    rank = first_relevant_rank(passages, q) if answerable else None
    ev_rank = evidence_rank(passages, q) if q.get("evidence_must_contain") else None
    facts = answer_has_facts(res["answer"], q.get("answer_must_contain", []))
    rel = q["relevant"]
    cited_relevant = None
    if answerable and res["sources"]:
        cited_relevant = any(
            s["chunk_id"].startswith(r["doc_id"] + ":") and ("page" not in r or s["page"] == r["page"])
            for s in res["sources"]
            for r in rel
        )
    # Retrieval is judged first: if the chunk containing the answer never reached the
    # prompt, a wrong answer is a retrieval failure, not a generation failure.
    evidence_missing = answerable and (rank is None or (q.get("evidence_must_contain") and ev_rank is None))
    if not answerable:
        verdict = "correct abstention" if res["abstained"] else "should have abstained"
    elif evidence_missing and facts is not False and not res["abstained"]:
        verdict = "ok (answered without the labelled evidence chunk)"
    elif rank is None:
        verdict = "retrieval: no relevant page retrieved"
    elif evidence_missing:
        verdict = "retrieval: relevant page retrieved, but not the chunk containing the answer"
    elif res["abstained"]:
        verdict = "generation: abstained despite evidence"
    elif facts is False:
        verdict = "generation: key facts missing/wrong"
    else:
        verdict = "ok"
    return {
        "page_rank": rank,
        "evidence_rank": ev_rank,
        "facts": facts,
        "cited_relevant": cited_relevant,
        "invalid_citations": res["invalid_citations"],
        "verdict": verdict,
    }


def run_examples(settings: Settings) -> None:
    questions = load_questions()
    pipe = RAGPipeline(settings)
    info = get_llm(settings).model_info()
    OUT_DIR.mkdir(parents=True, exist_ok=True)

    records, sections, rows = [], [], []
    for q in questions:
        print(f"[{q['id']}] {q['question']}")
        res = pipe.ask(q["question"])
        diag = _diagnose(q, res)
        res["example_id"], res["example_type"], res["diagnosis"] = q["id"], q["type"], diag
        records.append(res)
        print(f"   -> {diag['verdict']}  ({res['generation']['latency_s']} s)")
        sections.append(f"## {q['id']} ({q['type']})\n\n" + render_markdown(res) + f"\n*Diagnosis:* {diag['verdict']}\n")
        fmt = lambda v: "-" if v is None else ("yes" if v is True else ("no" if v is False else str(v)))
        na = not q["relevant"]
        rows.append(
            f"| {q['id']} | {q['type']} | {'n/a' if na else fmt(diag['page_rank'])} | "
            f"{'n/a' if na else (fmt(diag['evidence_rank']) if q.get('evidence_must_contain') else 'not labelled')} | "
            f"{fmt(diag['facts'])} | {fmt(diag['cited_relevant'])} | {fmt(res['abstained'])} | "
            f"{diag['invalid_citations'] or '-'} | {diag['verdict']} |"
        )

    with open(OUT_DIR / "answers.jsonl", "w", encoding="utf-8") as f:
        for r in records:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")

    s = settings
    header = [
        "# Example outputs",
        "",
        "Generated by `python -m rag examples`. Every answer below was produced by the system; nothing was edited by hand.",
        "",
        f"- LLM: `{info.get('model')}` via Ollama {info.get('ollama_version')} "
        f"({info.get('parameter_size')}, {info.get('quantization')}, digest `{(info.get('digest') or '')[:12]}`), "
        f"temperature={s.temperature}, seed={s.seed}, num_ctx={s.num_ctx}",
        f"- Embeddings: `{s.embed_model}`; retrieval: {s.retrieval_mode}, top_k={s.top_k}, candidate_k={s.candidate_k}",
        f"- Chunking: {s.chunk_size} chars, {s.chunk_overlap} overlap; context cap {s.max_context_chars} chars",
        "",
        "## Summary",
        "",
        "- page rank: rank of the first retrieved chunk from a labelled page; "
        "evidence rank: rank of the first retrieved chunk whose text contains the answer (`miss`/`-` if not in top-k).",
        "- key facts: answer contains the labelled strings (string match, checked by hand below). "
        "cited relevant: at least one citation points at a labelled page. "
        "invalid cites: bracketed numbers in the answer that match no passage.",
        "",
        "| id | type | page rank | evidence rank | key facts | cited relevant | abstained | invalid cites | verdict |",
        "|---|---|---|---|---|---|---|---|---|",
        *rows,
        "",
    ]
    (OUT_DIR / "answers.md").write_text("\n".join(header) + "\n" + "\n".join(sections), encoding="utf-8")
    print(f"\nSaved {len(records)} examples to {OUT_DIR}")
